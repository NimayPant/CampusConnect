import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, readdirSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn, spawnSync } from 'node:child_process';
import sharp from 'sharp';

test('Campus Connect complete API and storage workflow', async () => {
  const temporary = mkdtempSync(path.join(os.tmpdir(), 'campus-api-'));
  const env = { ...process.env, NODE_ENV: 'test', PORT: '4181', CAMPUS_DATA_DIR: temporary + '/data', CAMPUS_UPLOAD_DIR: temporary + '/uploads' };
  const base = 'http://127.0.0.1:4181/api';
  let server;
  const start = async () => {
    server = spawn(process.execPath, ['server/index.js'], { env });
    await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.stderr.on('data', data => { if (String(data).includes('Error')) reject(Error(String(data))); }); server.once('exit', code => reject(Error('Server exited ' + code))); });
  };
  const stop = async () => { const child = server; await new Promise(resolve => { child.once('exit', resolve); child.kill(); }); };
  const request = async (route, method = 'GET', data, cookie) => {
    const multipart = data instanceof FormData;
    const response = await fetch(base + route, { method, headers: { 'X-Campus-Request': '1', ...(cookie ? { Cookie: cookie } : {}), ...(multipart ? {} : { 'Content-Type': 'application/json' }) }, ...(data === undefined ? {} : { body: multipart ? data : JSON.stringify(data) }) });
    const body = response.status === 204 ? null : await response.json();
    return { status: response.status, body, cookie: response.headers.get('set-cookie')?.split(';')[0] };
  };
  const login = async (username, password) => { const result = await request('/auth/login', 'POST', { username, password }); assert.equal(result.status, 200); return result.cookie; };
  const collection = name => JSON.parse(readFileSync(temporary + '/data/' + name + '.json', 'utf8'));
  const seed = (...args) => { const result = spawnSync(process.execPath, ['server/seed.js', ...args], { env, encoding: 'utf8' }); assert.equal(result.status, 0, result.stderr); };
  try {
    seed();
    assert.equal(collection('events').length, 20);
    assert.equal(collection('users').length, 25);
    assert(collection('registrations').filter(item => item.status === 'active').length >= 40);
    assert(collection('feedback').length >= 25);
    const snapshot = readFileSync(temporary + '/data/users.json', 'utf8');
    seed();
    assert.equal(readFileSync(temporary + '/data/users.json', 'utf8'), snapshot);
    const userIds = new Set(collection('users').map(item => item.id));
    const eventIds = new Set(collection('events').map(item => item.id));
    for (const item of [...collection('registrations'), ...collection('feedback')]) { assert(userIds.has(item.userId)); assert(eventIds.has(item.eventId)); }
    assert(collection('users').every(item => item.passwordHash && !item.password));
    await start();
    assert.equal((await request('/events')).status, 401);
    let admin = await login('admin', 'Admin@12345');
    const student = await login('student', 'Student@12345');
    assert.equal((await request('/admin/stats', 'GET', undefined, student)).status, 403);
    for (const method of ['POST', 'PUT', 'DELETE']) assert.equal((await request('/events' + (method === 'POST' ? '' : '/event-01'), method, {}, student)).status, 403);
    let result = await request('/auth/register', 'POST', { username: 'newlearner', fullName: 'New Learner', email: 'new@example.com', password: 'Learning@123', role: 'admin' });
    assert.equal(result.status, 201);
    assert.equal(result.body.user.role, 'student');
    assert(!('passwordHash' in result.body.user));
    let newcomer = result.cookie;
    assert.equal((await request('/auth/register', 'POST', { username: 'newlearner', fullName: 'Other', email: 'other@example.com', password: 'Learning@123' })).status, 409);
    assert.equal((await request('/profile', 'PUT', { fullName: 'Updated Learner', email: 'updated@example.com' }, newcomer)).status, 200);
    assert.equal((await request('/profile', 'PUT', { fullName: 'Updated', email: 'student1@campus.example' }, newcomer)).status, 409);
    const future = { title: 'Capacity test', category: 'Workshop', date: '2035-12-01', time: '14:00', location: 'Lab 3', organizer: 'Test Club', description: 'Capacity and concurrency check.', capacity: 1 };
    result = await request('/events', 'POST', future, admin);
    assert.equal(result.status, 201);
    const id = result.body.id;
    const race = await Promise.all([request('/events/' + id + '/register', 'POST', {}, newcomer), request('/events/' + id + '/register', 'POST', {}, student)]);
    assert.deepEqual(race.map(item => item.status).sort(), [201, 409]);
    const winner = race[0].status === 201 ? newcomer : student;
    assert.equal((await request('/events/' + id + '/register', 'POST', {}, winner)).status, 409);
    assert.equal((await request('/events/' + id, 'GET', undefined, admin)).body.remainingSeats, 0);
    assert.equal((await request('/events/' + id, 'PUT', { ...future, capacity: 0 }, admin)).status, 400);
    assert.equal((await request('/events/' + id + '/register', 'DELETE', undefined, winner)).status, 204);
    assert.equal((await request('/events/' + id, 'GET', undefined, admin)).body.remainingSeats, 1);
    assert.equal((await request('/events/' + id + '/register', 'POST', { userId: 'someone-else' }, newcomer)).status, 403);
    assert.equal((await request('/events/' + id + '/feedback', 'POST', { rating: 5 }, newcomer)).status, 409);
    assert.equal((await request('/events/event-01/register', 'POST', {}, newcomer)).status, 409);
    assert.equal((await request('/events/event-01/feedback', 'POST', { rating: 5 }, newcomer)).status, 403);
    assert.equal((await request('/events/event-01/feedback', 'PUT', { rating: 6 }, student)).status, 400);
    assert.equal((await request('/events/event-01/feedback', 'PUT', { rating: 4, comment: 'Updated feedback.' }, student)).status, 200);
    assert.equal((await request('/events/event-01/feedback', 'POST', { rating: 5 }, student)).status, 409);
    const feedback = (await request('/events/event-01/feedback', 'GET', undefined, student)).body.items[0];
    assert.equal((await request('/admin/feedback/' + feedback.id, 'DELETE', undefined, student)).status, 403);
    assert.equal((await request('/admin/feedback/' + feedback.id, 'DELETE', undefined, admin)).status, 204);
    const png = await sharp({ create: { width: 40, height: 40, channels: 3, background: '#28543f' } }).png().toBuffer();
    const form = (bytes, mime = 'image/png') => { const body = new FormData(); for (const [key, value] of Object.entries({ ...future, imageAlt: 'Green test poster for the capacity workshop' })) body.append(key, String(value)); body.append('poster', new Blob([bytes], { type: mime }), '../../unsafe.png'); return body; };
    result = await request('/events', 'POST', form(png), admin);
    assert.equal(result.status, 201);
    assert.match(result.body.imageFilename, /^[a-f0-9-]+\.webp$/);
    const posterId = result.body.id, oldFilename = result.body.imageFilename;
    assert.equal((await request('/events/' + posterId, 'PUT', form(png), admin)).status, 200);
    assert(!readdirSync(temporary + '/uploads').includes(oldFilename));
    assert.equal((await request('/events', 'POST', form(Buffer.from('fake image')), admin)).status, 415);
    assert.equal((await request('/events', 'POST', form(png, 'image/svg+xml'), admin)).status, 415);
    assert.equal((await request('/events', 'POST', form(Buffer.alloc(5 * 1024 * 1024 + 1)), admin)).status, 413);
    assert.equal((await request('/profile/password', 'PUT', { currentPassword: 'wrong', newPassword: 'Replacement@123' }, newcomer)).status, 400);
    const otherSession = await login('newlearner', 'Learning@123');
    result = await request('/profile/password', 'PUT', { currentPassword: 'Learning@123', newPassword: 'Replacement@123' }, newcomer);
    assert.equal(result.status, 200);
    newcomer = result.cookie;
    assert.equal((await request('/events', 'GET', undefined, otherSession)).status, 401);
    await stop();
    await start();
    assert.equal((await request('/events', 'GET', undefined, newcomer)).status, 401);
    newcomer = await login('newlearner', 'Replacement@123');
    assert.equal((await request('/profile', 'GET', undefined, newcomer)).body.fullName, 'Updated Learner');
    assert.equal((await request('/events/' + posterId, 'GET', undefined, newcomer)).status, 200);
    admin = await login('admin', 'Admin@12345');
    assert.equal((await request('/events/' + id, 'DELETE', undefined, admin)).status, 204);
    assert.equal((await request('/events/' + id + '/register', 'POST', {}, newcomer)).status, 404);
    const stats = (await request('/admin/stats', 'GET', undefined, admin)).body;
    assert.equal(stats.totalStudents, 25);
    assert.equal(stats.activeRegistrations, stats.events.reduce((sum, event) => sum + event.registeredCount, 0));
    for (let i = 0; i < 10; i++) assert.equal((await request('/auth/login', 'POST', { username: 'nobody', password: 'wrong' })).status, 401);
    assert.equal((await request('/auth/login', 'POST', { username: 'nobody', password: 'wrong' })).status, 429);
    await stop();
    const old = collection('events'); delete old[0].capacity; delete old[0].updatedAt; writeFileSync(temporary + '/data/events.json', JSON.stringify(old));
    seed();
    assert.equal(collection('events')[0].capacity, 50);
    assert(collection('events').some(event => event.id === posterId));
    seed('--reset', '--yes');
    assert.equal(collection('events').length, 20);
    assert.equal(collection('users').length, 25);
    assert(readdirSync(temporary + '/backups').length > 0);
  } finally { if (server && server.exitCode === null) server.kill(); }
});
